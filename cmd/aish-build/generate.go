package main

import (
	"errors"
	"fmt"
	"maps"
	"path/filepath"
	"slices"
	"strings"
)

// standardPackage is modules/standard, which blank-imports the standard build.
const standardPackage = corePath + "/modules/standard"

type options struct {
	With    []string // <module path>[@version][=<local dir>]
	Without []string // standard packages relative to modules/, e.g. "llm/anthropic"
	Core    string   // local aish-core checkout, optional
}

type plugin struct {
	path, version, dir string
}

func parseWith(spec string) (plugin, error) {
	left, dir, _ := strings.Cut(spec, "=")
	path, version, _ := strings.Cut(left, "@")
	if path == "" {
		return plugin{}, fmt.Errorf("aish-build: invalid --with %q, want <module path>[@version][=<local dir>]", spec)
	}
	if dir != "" {
		abs, err := filepath.Abs(dir)
		if err != nil {
			return plugin{}, fmt.Errorf("aish-build: --with %q: %w", spec, err)
		}
		dir = abs
	}

	return plugin{path: path, version: version, dir: dir}, nil
}

// generate returns main.go and go.mod of a build that links the standard
// packages std (minus o.Without) and the plugins of o.With. Versions that are
// not pinned are left for `go mod tidy` to resolve.
func generate(o options, std []string) (map[string]string, error) {
	imports, err := without(std, o.Without)
	if err != nil {
		return nil, err
	}
	var requires, replaces []string
	if o.Core != "" {
		abs, err := filepath.Abs(o.Core)
		if err != nil {
			return nil, fmt.Errorf("aish-build: --core: %w", err)
		}
		requires = append(requires, corePath+" v0.0.0")
		replaces = append(replaces, fmt.Sprintf("%s => %s", corePath, abs))
	}
	for _, spec := range o.With {
		p, err := parseWith(spec)
		if err != nil {
			return nil, err
		}
		imports = append(imports, p.path)
		switch {
		case p.dir != "":
			requires = append(requires, p.path+" v0.0.0")
			replaces = append(replaces, fmt.Sprintf("%s => %s", p.path, p.dir))
		case p.version != "":
			requires = append(requires, p.path+" "+p.version)
		default:
		}
	}
	slices.Sort(imports)

	var mainGo strings.Builder
	fmt.Fprintf(&mainGo, "// Code generated by aish-build. DO NOT EDIT.\npackage main\n\nimport (\n\t\"fmt\"\n\t\"os\"\n\n\t\"%s/app\"\n", corePath)
	for _, imp := range slices.Compact(imports) {
		fmt.Fprintf(&mainGo, "\t_ \"%s\"\n", imp)
	}
	mainGo.WriteString(")\n\nfunc main() {\n\tif err := app.Run(); err != nil {\n\t\tfmt.Fprintln(os.Stderr, err)\n\t\tos.Exit(1)\n\t}\n}\n")

	var goMod strings.Builder
	fmt.Fprintf(&goMod, "module aish-build-output\n\ngo %s\n", goVersion)
	for _, r := range requires {
		fmt.Fprintf(&goMod, "\nrequire %s\n", r)
	}
	for _, r := range replaces {
		fmt.Fprintf(&goMod, "\nreplace %s\n", r)
	}

	return map[string]string{"main.go": mainGo.String(), "go.mod": goMod.String()}, nil
}

// without drops the packages named by excluded, which are relative to
// modules/.
func without(std, excluded []string) ([]string, error) {
	drop := map[string]bool{}
	for _, e := range excluded {
		drop[corePath+"/modules/"+e] = true
	}
	var kept []string
	for _, pkg := range std {
		if drop[pkg] {
			delete(drop, pkg)

			continue
		}
		kept = append(kept, pkg)
	}
	errs := make([]error, 0, len(drop))
	for _, pkg := range slices.Sorted(maps.Keys(drop)) {
		errs = append(errs, fmt.Errorf("aish-build: --without %s: not a package of the standard build", strings.TrimPrefix(pkg, corePath+"/modules/")))
	}

	return kept, errors.Join(errs...)
}
